String _normalizeNfc(String text, Map<String, String> p) {
  if (!text.contains('\u0300') &&
      !text.contains('\u0301') &&
      !text.contains('\u0302') &&
      !text.contains('\u0303') &&
      !text.contains('\u0308') &&
      !text.contains('\u030A') &&
      !text.contains('\u0327')) {
    return text;
  }
  var out = text;
  for (final e in _nfcCombos.entries) {
    out = out.replaceAll(e.key, e.value);
  }
  return out;
