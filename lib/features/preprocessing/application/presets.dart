/// 预置功能。
///
/// 每条预置功能有：
///   - id：稳定标识，存进 PreprocessingRule.presetId
///   - name：显示名
///   - description：一句话说明
///   - helpText：详细说明（对话框灰框显示）
///   - params：参数定义（UI 根据它生成表单）
///   - apply：真正干活的函数
///   - implType / implDetail：实现方式（正则原文 或 代码片段）
///   - replacementType / replacementDetail / replacementNote：替代方案
///
/// 参数在存储里都是字符串（Map<String, String>）。
/// 执行时用 _pInt / _pStr / _pBool 安全解析。

import 'dart:convert';

// ==================== 参数 ====================

/// 参数类型。UI 根据它决定用什么控件。
enum PresetParamType {
  /// 单行文本输入。
  text,

  /// 整数输入（数字键盘）。
  integer,

  /// 下拉选择。
  choice,
}

/// 一个参数的定义。
class PresetParam {
  const PresetParam({
    required this.key,
    required this.label,
    required this.type,
    this.defaultValue = '',
    this.options = const <String>[],
    this.hint = '',
  });

  final String key;
  final String label;
  final PresetParamType type;
  final String defaultValue;

  /// type == choice 时用。每项格式 'value|显示名'，无 '|' 则 value = 显示名。
  final List<String> options;

  final String hint;

  String labelFor(String value) {
    for (final o in options) {
      final idx = o.indexOf('|');
      if (idx < 0) {
        if (o == value) return o;
      } else {
        if (o.substring(0, idx) == value) return o.substring(idx + 1);
      }
    }
    return value;
  }
}

// ==================== Preset ====================

class Preset {
  const Preset({
    required this.id,
    required this.name,
    required this.description,
    required this.helpText,
    required this.params,
    required this.apply,
    this.implType,
    this.implDetail,
    this.replacementType,
    this.replacementDetail,
    this.replacementNote,
  });

  final String id;
  final String name;
  final String description;
  final String helpText;
  final List<PresetParam> params;
  final String Function(String text, Map<String, String> params) apply;

  /// 实现方式类型。'正则' 或 '代码'。null 时不显示"实现方式"块。
  final String? implType;

  /// 实现方式详情。正则原文 或 关键代码片段。
  final String? implDetail;

  /// 替代方案状态。'ok' / 'warn' / 'impossible'。null 时不显示。
  final String? replacementType;

  /// 替代方案详情。
  final String? replacementDetail;

  /// 替代方案额外备注（可选）。
  final String? replacementNote;
}

